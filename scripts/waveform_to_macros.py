#!/usr/bin/env python3
"""Write the PDS waveform-characterisation numbers (HD vs VD) as LaTeX macros and the parameter table.

Usage:  <python with pandas> LOWE_RECONSTRUCTION_PUBLICATION/scripts/waveform_to_macros.py [DATA_DIR] [-o results/waveform_macros.tex]
                                                          [-t tables/pds_waveform_parameters.tex]

DATA_DIR holds the SOLAR waveform export (src/tools/export_waveform_repo.py), synced by
LOWE_RECONSTRUCTION_PUBLICATION/scripts/sync_solar_data.sh --waveform (default: that repository's copy).
All values come from the Matched flashes (the flash matched to each TPC cluster) with MARLEY light
(Signal == "Signal").

Macro names: \\wf<Det><Qty><Bin>, letters only.
  Det  HD   hd_1x2x6_centralAPA / marley_waveform           (HD Central, pure LAr)
       VD   vd_1x8x14_3view_30deg_nominal / marley_flash    (VD Top, 10 ppm Xe)
  Bin  All, Low (5-20 PE), Mid (20-100 PE), High (100-1000 PE), Max (>1000 PE): PE of the main OpHit
  Qty  per-waveform medians PeakTime RiseTime TFifty TNinety TNinetyNine FWHM (us) ADCperPE SecondaryFrac,
       <Qty>Range the 16-84 % interval (Bin All only), NWaveforms, NJobs;
       single-photoelectron response \\wfSPE<Det><Qty>: PeakTime (us after the start), Amplitude (ADC),
       FallTime (1/e, us after the peak), ZeroCross and UndershootTime (us), Undershoot (fraction).
"""
import argparse
import os
from pathlib import Path

import numpy as np
import pandas as pd

# Thesis repository (outputs go to its results/ and tables/); override with THESIS_DIR.
ROOT = Path(os.environ.get("THESIS_DIR", Path.home() / "Code" / "THESIS"))
DEFAULT_DATA = Path("/home/smanthey/Code/LOWE_RECONSTRUCTION_PUBLICATION/input/data/PDS/waveform")
SAMPLES = {
    "HD": ("hd_1x2x6_centralAPA", "marley_waveform", "Signal"),
    "VD": ("vd_1x8x14_3view_30deg_nominal", "marley_flash", "Signal"),
}
BINS = {"All": "All", "Low": "5-20", "Mid": "20-100", "High": "100-1000", "Max": ">1000"}
TIMES = {"PeakTime": "PeakTime", "RiseTime": "RiseTime", "TFifty": "T50", "TNinety": "T90",
         "TNinetyNine": "T99", "FWHM": "FWHM"}
US = r"\micro\second"


def select(df, det, pe):
    config, name, signal = SAMPLES[det]
    rows = df[(df.Config == config) & (df.Name == name) & (df.Source == "Matched")
              & (df.Signal == signal) & (df.PEBin == pe)]
    if len(rows) > 1:
        raise SystemExit(f"{det} {pe}: {len(rows)} rows, expected one")
    return rows.iloc[0] if len(rows) else None


def qty(x, digits=2):
    return rf"\qty{{{x:.{digits}f}}}{{{US}}}"


def macro(name, value, comment=""):
    return rf"\newcommand{{\{name}}}{{{value}\xspace}}" + (f"  % {comment}" if comment else "")


def spe_numbers(spe):
    out = {}
    for _, r in spe.iterrows():
        det = r.Geometry.upper()
        t, n, adc = (np.asarray(r[c], float) for c in ("Time", "Normalised", "ADC"))
        ip = int(n.argmax())
        late = t > t[ip]
        out[det] = {"PeakTime": t[ip], "Amplitude": adc.max(),
                    "FallTime": t[late & (n < np.exp(-1))][0] - t[ip]}
        if n.min() < -0.01:
            out[det].update(ZeroCross=t[late & (n < 0)][0], Undershoot=n.min(), UndershootTime=t[n.argmin()])
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("data", nargs="?", type=Path, default=DEFAULT_DATA)
    parser.add_argument("-o", "--output", type=Path, default=ROOT / "results" / "waveform_macros.tex")
    parser.add_argument("-t", "--table", type=Path, default=ROOT / "tables" / "pds_waveform_parameters.tex")
    args = parser.parse_args()

    summary = pd.read_pickle(args.data / "waveform_summary.pkl")
    spe = pd.read_pickle(args.data / "spe_responses.pkl")
    meta = (args.data / "meta.json").read_text() if (args.data / "meta.json").exists() else ""
    generated = next((l.split('"')[3] for l in meta.splitlines() if '"generated"' in l), "unknown")

    lines = ["% Generated by LOWE_RECONSTRUCTION_PUBLICATION/scripts/waveform_to_macros.py from the SOLAR PDS waveform export "
             f"(generated {generated}); do not edit by hand.",
             "% Matched flashes with MARLEY light.", ""]
    for det in SAMPLES:
        for tag, pe in BINS.items():
            s = select(summary, det, pe)
            if s is None:
                continue
            for name, col in TIMES.items():
                lines.append(macro(f"wf{det}{name}{tag}", qty(s[f"{col}Median"])))
                if tag == "All":
                    lines.append(macro(f"wf{det}{name}Range{tag}",
                                       rf"\qtyrange{{{s[f'{col}P16']:.2f}}}{{{s[f'{col}P84']:.2f}}}{{{US}}}"))
            lines.append(macro(f"wf{det}ADCperPE{tag}", rf"\num{{{s.ADCperPEMedian:.1f}}}"))
            lines.append(macro(f"wf{det}SecondaryFrac{tag}", rf"\num{{{s.SecondaryPulseFraction:.2f}}}"))
            lines.append(macro(f"wf{det}NWaveforms{tag}", rf"\num{{{int(s.NClean)}}}"))
            if tag == "All":
                lines.append(macro(f"wf{det}NJobs", rf"\num{{{int(s.NInputs)}}}"))
        lines.append("")

    for det, values in spe_numbers(spe).items():
        for name, value in values.items():
            if name == "Amplitude":
                text = rf"\qty{{{value:.1f}}}{{\ADC}}"
            elif name == "Undershoot":
                text = rf"\num{{{value:.2f}}}"
            elif name == "PeakTime":
                text = rf"\qty{{{value * 1e3:.0f}}}{{\nano\second}}"
            else:
                text = qty(value, 2)
            lines.append(macro(f"wfSPE{det}{name}", text))
    args.output.write_text("\n".join(lines) + "\n")
    print(f"wrote {args.output} ({sum(l.startswith(chr(92)) for l in lines)} macros)")

    hd, vd = select(summary, "HD", "All"), select(summary, "VD", "All")

    def interval(s, col):
        return rf"\num{{{s[f'{col}Median']:.2f}}} (\numrange{{{s[f'{col}P16']:.2f}}}{{{s[f'{col}P84']:.2f}}})"

    rows = [("Waveforms", rf"\num{{{int(hd.NClean)}}}", rf"\num{{{int(vd.NClean)}}}")]
    labels = {"PeakTime": r"Onset to peak (\unit{\micro\second})", "RiseTime": r"Rise time 10--90\,\% (\unit{\micro\second})",
              "T50": r"$T_{50}$ (\unit{\micro\second})", "T90": r"$T_{90}$ (\unit{\micro\second})",
              "T99": r"$T_{99}$ (\unit{\micro\second})", "FWHM": r"FWHM (\unit{\micro\second})"}
    rows += [(label, interval(hd, col), interval(vd, col)) for col, label in labels.items()]
    rows.append((r"Peak amplitude per PE (ADC/PE)", rf"\num{{{hd.ADCperPEMedian:.1f}}}", rf"\num{{{vd.ADCperPEMedian:.1f}}}"))
    table = [f"% Generated by LOWE_RECONSTRUCTION_PUBLICATION/scripts/waveform_to_macros.py (SOLAR PDS waveform export, generated {generated}); do not edit by hand.",
             r"\begin{tabular}{lcc}", r"    \toprule", r"    Parameter & \HD & \VD \\", r"    \midrule"]
    # rows kept in the source but commented out of the thesis table
    hidden = {"Waveforms", labels["PeakTime"], labels["FWHM"]}
    table += [f"    {'% ' if a in hidden else ''}{a} & {b} & {c} \\\\" for a, b, c in rows]
    table += [r"    \bottomrule", r"\end{tabular}"]
    args.table.write_text("\n".join(table) + "\n")
    print(f"wrote {args.table}")


if __name__ == "__main__":
    main()
